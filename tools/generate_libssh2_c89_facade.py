def transform(text: str) -> str:
    text = text.replace("LIBSSH2CHANNEL_", "CPKT_LIBSSH2_CHANNEL_")
    text = text.replace("LIBSSH2SFTP_", "CPKT_LIBSSH2_SFTP_")
    text = re.sub(r"(?<!CPKT_)LIBSSH2_", "CPKT_LIBSSH2_", text)
    text = text.replace("libssh2_", "cpkt_libssh2_")
    for native, facade in REPLACEMENTS:
        text = re.sub(r"\b" + re.escape(native) + r"\b", facade, text)
    for upper, lower in (
            ("SESSION", "session"), ("CHANNEL", "channel"),
            ("LISTENER", "listener"), ("KNOWNHOSTS", "knownhosts"),
            ("AGENT", "agent"), ("SFTP_HANDLE", "sftp_handle"),
            ("SFTP_ATTRIBUTES", "sftp_attributes"),
            ("SFTP_STATVFS", "sftp_statvfs_t"), ("SFTP", "sftp"),
            ("PUBLICKEY", "publickey")):
        text = re.sub(r"\bCPKT_LIBSSH2_" + upper + r"\b",
                      "cpkt_libssh2_" + lower, text)
    return text


def trim_header(text: str, name: str) -> str:
    if name == "libssh2.h":
        start = text.find("/* Part of every banner")
        end = text.rfind("#ifdef __cplusplus")
    elif name == "libssh2_sftp.h":
        start = text.find("#define LIBSSH2_SFTP_VERSION")
        end = text.rfind("#ifdef __cplusplus")
    else:
        start = text.find("typedef struct _LIBSSH2_PUBLICKEY")
        end = text.rfind("#ifdef __cplusplus")
    if start < 0 or end < 0:
        raise ValueError("unable to locate public body in " + name)
    return text[start:end]


def strip_redeclared_types(body: str) -> str:
    names = (
        "LIBSSH2_SESSION", "LIBSSH2_CHANNEL", "LIBSSH2_LISTENER",
        "LIBSSH2_KNOWNHOSTS", "LIBSSH2_AGENT", "LIBSSH2_SFTP",
        "LIBSSH2_SFTP_HANDLE", "LIBSSH2_SFTP_ATTRIBUTES",
        "LIBSSH2_SFTP_STATVFS", "LIBSSH2_PUBLICKEY",
    )
    for name in names:
        body = re.sub(
            r"typedef struct _" + name + r"\s+" + name + r"\s*;\s*",
            "", body)
    for name in ("_LIBSSH2_SFTP_ATTRIBUTES", "_LIBSSH2_SFTP_STATVFS"):
        body = re.sub(
            r"struct " + name + r"\s*\{.*?\}\s*;\s*",
            "", body, flags=re.DOTALL)
    return body


