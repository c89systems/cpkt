SOURCE = r'''/* Generated by tools/generate_zlibng_c89_facade.py. */
#define _FILE_OFFSET_BITS 64
#define _LARGEFILE64_SOURCE 1
#define WITH_GZFILEOP 1
#include <zlib-ng.h>
#define CPKT_ZLIBNG_NATIVE_TYPES
#include <cpkt/zlibng.h>
#include <limits.h>
#include <stdint.h>
#include <string.h>

typedef char cpkt_zlibng_byte_matches[__builtin_types_compatible_p(uint8_t, unsigned char) ? 1 : -1];
typedef char cpkt_zlibng_u32_matches[__builtin_types_compatible_p(uint32_t, unsigned int) ? 1 : -1];
typedef char cpkt_zlibng_i32_matches[__builtin_types_compatible_p(int32_t, int) ? 1 : -1];
typedef char cpkt_zlibng_param_matches[__builtin_types_compatible_p(zng_deflate_param, unsigned int) ? 1 : -1];
typedef char cpkt_zlibng_word_is_32[(sizeof(unsigned int) * CHAR_BIT == 32) ? 1 : -1];
typedef char cpkt_zlibng_offset_is_64[(sizeof(z_off64_t) * CHAR_BIT == 64) ? 1 : -1];

static z_off64_t cpkt_zlibng_offset_to_native(cpkt_zlibng_off64 value) {
  uint64_t bits = ((uint64_t)value.high << 32) | value.low;
  z_off64_t result;
  memcpy(&result, &bits, sizeof(result));
  return result;
}
static cpkt_zlibng_off64 cpkt_zlibng_offset_from_native(z_off64_t value) {
  uint64_t bits;
  cpkt_zlibng_off64 result;
  memcpy(&bits, &value, sizeof(bits));
  result.high = (unsigned int)(bits >> 32);
  result.low = (unsigned int)bits;
  return result;
}

@DEFINITIONS@
'''


def generate(args):
    native = (args.include_dir / "zlib-ng.h").read_text()
    functions = declarations(native)
    constants = []
    for name, value in re.findall(r"^#define (Z_\w+)\s+([^\n]+)", native, re.M):
        value = re.sub(r"/\*.*?\*/", "", value).strip()
        value = re.sub(r"\bZ_", "CPKT_ZLIBNG_", value)
        constants.append("#define " + name.replace("Z_", "CPKT_ZLIBNG_", 1) + " " + value)
    constants.extend("#define CPKT_ZLIBNG_" + name + " " + value
                     for name, value in re.findall(r"\bZ_(DEFLATE_\w+)\s*=\s*(\d+)", native))
    version = re.search(r'#define ZLIBNG_VERSION "([^"]+)"', native).group(1)
    constants.append('#define CPKT_ZLIBNG_VERSION "' + version + '"')
    for suffix, value in re.findall(r"^#define ZLIBNG_(VER\w*)\s+([^\n]+)", native, re.M):
        if suffix == "VERSION":
            continue
        value = re.sub(r"/\*.*?\*/", "", value).strip()
        constants.append("#define CPKT_ZLIBNG_" + suffix + " " + value)
    prototypes, definitions, surface_declarations, surface_checks = [], [], [], []
    for returns, name, parameters in functions:
        public = public_name(name)
        signature = ", ".join(transform(kind) + (" " + arg if arg else "")
                              for kind, arg in parameters) or "void"
        declaration = "CPKT_ZLIBNG_API {} {}({})".format(transform(returns), public, signature)
        prototypes.append(declaration + ";")
        surface_declarations.append("  {} (*volatile reference_{})({}) = &{};".format(
            transform(returns), public, signature, public))
        surface_checks.append("  if (reference_{} == NULL) return 1;".format(public))
        definition = declaration + " {\n"
        if name == "zng_gzprintf":
            definition += ("  va_list arguments;\n  int result;\n"
                           "  va_start(arguments, format);\n"
                           "  result = zng_gzvprintf((gzFile)file, format, arguments);\n"
                           "  va_end(arguments);\n  return result;\n")
        else:
            passed = ["cpkt_zlibng_offset_to_native({})".format(arg)
                      if kind == "z_off64_t" else "(gzFile)" + arg
                      if kind == "gzFile" else arg for kind, arg in parameters]
            call = "({})({})".format(name, ", ".join(passed))
            if returns == "z_off64_t":
                call = "cpkt_zlibng_offset_from_native({})".format(call)
            elif returns == "gzFile":
                call = "(cpkt_zlibng_gzfile)" + call
            definition += "  " + ("return " if returns != "void" else "") + call + ";\n"
        definitions.append(definition + "}\n")
    license_start = native.index("/* zlib-ng.h")
    license_end = native.index("*/", license_start) + 2
    header = native[license_start:license_end] + "\n" + HEADER
    header = header.replace("@CONSTANTS@", "\n".join(constants))
    header = header.replace("@DECLARATIONS@", "\n".join(prototypes))
    source = SOURCE.replace("@DEFINITIONS@", "\n".join(definitions))
    outputs = [args.header, args.source]
    if args.surface:
        outputs.append(args.surface)
    validate_output_paths(*outputs)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.source.parent.mkdir(parents=True, exist_ok=True)
    write_generated_text(args.header, header)
    write_generated_text(args.source, source)
    if args.surface:
        args.surface.parent.mkdir(parents=True, exist_ok=True)
        write_generated_text(args.surface, "#include <cpkt/zlibng.h>\nint main(void) {\n"
                             + "\n".join(surface_declarations + surface_checks)
                             + "\n  return 0;\n}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--include-dir", type=pathlib.Path, required=True)
    parser.add_argument("--header", type=pathlib.Path, required=True)
    parser.add_argument("--source", type=pathlib.Path, required=True)
    parser.add_argument("--surface", type=pathlib.Path)
    generate(parser.parse_args())
